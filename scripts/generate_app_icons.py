#!/usr/bin/env python3
"""Generate the alternate app icons (dark, mono, pink) from assets/images/tsdm_client.png.

Run from the repository root with Pillow installed:  python3 scripts/generate_app_icons.py

Writes, for every variant:
  * Android: legacy mipmaps, an adaptive icon, its foreground vector and background colour.
  * iOS: an alternate app icon set (single 1024 px image) in Runner/Assets.xcassets.
  * assets/images/app_icons/<name>.png, the previews of the settings dialog.
The vector paths of the default foreground are re-coloured, so the variants follow the default artwork.
"""

import json
import re
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'assets/images/tsdm_client.png'
RES = ROOT / 'android/app/src/main/res'
XCASSETS = ROOT / 'ios/Runner/Assets.xcassets'
PREVIEWS = ROOT / 'assets/images/app_icons'

# The four blues of the artwork (icCls1..4 in res/values/colors.xml), darkest first by luminance, then the variants.
DEFAULT = {'bg': '#ffffff', 'cls': ['#01579b', '#54c5f8', '#29b6f6', '#19a6e6']}
VARIANTS = {
    'dark': {'bg': '#0b0e13', 'cls': ['#29b6f6', '#b3e5fc', '#81d4fa', '#4fc3f7']},
    'mono': {'bg': '#ffffff', 'cls': ['#424242', '#9e9e9e', '#757575', '#616161']},
    'pink': {'bg': '#fff0f5', 'cls': ['#ad1457', '#f48fb1', '#ec407a', '#d81b60']},
}
LEGACY_SIZES = {'mdpi': 48, 'hdpi': 72, 'xhdpi': 96, 'xxhdpi': 144, 'xxxhdpi': 192}


def rgb(value):
    return tuple(int(value[i : i + 2], 16) for i in (1, 3, 5))


def lum(c):
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]


def gradient_map(glyph, palette):
    """Re-colour [glyph] (RGBA, the default blues) to [palette], keeping its alpha and anti-aliasing."""
    src = sorted((lum(rgb(c)), i) for i, c in enumerate(DEFAULT['cls']))
    stops = [(l, rgb(palette['cls'][i])) for l, i in src]
    out = Image.new('RGBA', glyph.size)
    px, dst = glyph.load(), out.load()
    for y in range(glyph.size[1]):
        for x in range(glyph.size[0]):
            r, g, b, a = px[x, y]
            if a == 0:
                continue
            l = lum((r, g, b))
            if l <= stops[0][0]:
                c = stops[0][1]
            elif l >= stops[-1][0]:
                c = stops[-1][1]
            else:
                c = stops[-1][1]
                for (l0, c0), (l1, c1) in zip(stops, stops[1:]):
                    if l0 <= l <= l1:
                        t = (l - l0) / (l1 - l0) if l1 > l0 else 0
                        c = tuple(round(c0[k] + (c1[k] - c0[k]) * t) for k in range(3))
                        break
            dst[x, y] = (*c, a)
    return out


def compose(glyph, palette, size, scale, rounded):
    """The glyph on the background colour, as a [size] square (rounded corners for the Android legacy icons)."""
    canvas = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    bg = Image.new('RGBA', (size, size), (*rgb(palette['bg']), 255))
    if rounded:
        mask = Image.new('L', (size * 4, size * 4), 0)
        ImageDraw.Draw(mask).rounded_rectangle((0, 0, size * 4 - 1, size * 4 - 1), radius=size * 4 * 0.22, fill=255)
        canvas.paste(bg, mask=mask.resize((size, size), Image.LANCZOS))
    else:
        canvas = bg
    inner = round(size * scale)
    g = glyph.resize((inner, inner), Image.LANCZOS)
    canvas.alpha_composite(g, ((size - inner) // 2, (size - inner) // 2))
    return canvas


def foreground_xml(palette):
    text = (RES / 'drawable-nodpi/ic_launcher_foreground.xml').read_text()
    for index, color in enumerate(palette['cls'], start=1):
        text = text.replace(f'@color/icCls{index}', color)
    return text


def main():
    source = Image.open(SOURCE).convert('RGBA')
    PREVIEWS.mkdir(parents=True, exist_ok=True)
    compose(source, DEFAULT, 192, 0.8, rounded=True).save(PREVIEWS / 'default.png')

    colors = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated by scripts/generate_app_icons.py. -->', '<resources>']
    for name, palette in VARIANTS.items():
        glyph = gradient_map(source, palette)
        compose(glyph, palette, 192, 0.8, rounded=True).save(PREVIEWS / f'{name}.png')

        for density, size in LEGACY_SIZES.items():
            target = RES / f'mipmap-{density}/ic_launcher_{name}.png'
            compose(glyph, palette, size, 0.8, rounded=True).save(target)
        (RES / f'drawable-nodpi/ic_launcher_foreground_{name}.xml').write_text(foreground_xml(palette))
        (RES / f'mipmap-anydpi-v26/ic_launcher_{name}.xml').write_text(
            '<?xml version="1.0" encoding="utf-8"?>\n'
            '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
            f'    <background android:drawable="@color/ic_launcher_background_{name}" />\n'
            f'    <foreground android:drawable="@drawable/ic_launcher_foreground_{name}" />\n'
            f'    <monochrome android:drawable="@drawable/ic_launcher_foreground_{name}" />\n'
            '</adaptive-icon>\n'
        )
        colors.append(f'    <color name="ic_launcher_background_{name}">{palette["bg"]}</color>')

        iconset = XCASSETS / f'AppIcon{name.capitalize()}.appiconset'
        iconset.mkdir(parents=True, exist_ok=True)
        compose(glyph, palette, 1024, 0.8, rounded=False).convert('RGB').save(iconset / 'Icon-1024.png')
        (iconset / 'Contents.json').write_text(
            json.dumps(
                {
                    'images': [{'filename': 'Icon-1024.png', 'idiom': 'universal', 'platform': 'ios', 'size': '1024x1024'}],
                    'info': {'author': 'xcode', 'version': 1},
                },
                indent=2,
            )
            + '\n'
        )
    colors.append('</resources>')
    (RES / 'values/ic_launcher_variants.xml').write_text('\n'.join(colors) + '\n')


if __name__ == '__main__':
    main()
