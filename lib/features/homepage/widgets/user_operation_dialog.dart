/// Dialog for user operations.
///
/// With more than one account saved on this device it starts with the other accounts: one tap switches to one of
/// them (GitHub #184 follow-up), without going through the manage accounts page.
class UserOperationDialog extends StatefulWidget {
  /// Constructor.
  const UserOperationDialog({
    required this.username,
    required this.avatarUrl,
    required this.heroTag,
    required this.latestThreadUrl,
    super.key,
  });

  /// Username
  final String username;

  /// User avatar url.
  ///
  /// Can be null.
  final String? avatarUrl;

  /// Tag for user avatar hero.
  final String heroTag;

  /// Url of latest thread page.
  ///
  /// The latest thread url is a dynamic url generated by server.
  final String? latestThreadUrl;

  @override
  State<UserOperationDialog> createState() => _UserOperationDialogState();
}

class _UserOperationDialogState extends State<UserOperationDialog> with LoggerMixin {
  /// Other accounts listed at most; the rest are behind a row opening the manage accounts page, so the menu below
  /// stays in reach on a phone.
  static const _maxAccounts = 4;

  static final _tileShape = RoundedRectangleBorder(borderRadius: BorderRadius.circular(appInnerRadius));

  /// Null where the app's providers are missing (tests of other widgets): no account list then.
  AuthenticationRepository? _auth;

  /// Saved accounts, subscribed once: the drift stream queries again for every new subscriber.
  Stream<List<StoredAccount>>? _accounts;

  /// Runs the switches started here; closing it with the dialog ends nothing else (see [switchAccount]).
  SwitchUserBloc? _switchUserBloc;

  /// Uid of the account being switched to; while set the dialog cannot be dismissed and every entry waits.
  int? _switchingUid;

  bool get _switching => _switchingUid != null;

  @override
  void initState() {
    super.initState();
    _auth = context.readOrNull<AuthenticationRepository>();
    if (_auth != null) {
      _accounts = getIt.get<StorageProvider>().allAccountsStream();
      _switchUserBloc = SwitchUserBloc(_auth!);
    }
  }

  @override
  void dispose() {
    unawaited(_switchUserBloc?.close());
    super.dispose();
  }

  /// A row of the menu: icon, title, rounded ink; closes the menu and opens [screen].
  Widget _entry(BuildContext context, IconData icon, String title, String screen) => ListTile(
    leading: Icon(icon),
    title: Text(title),
    shape: _tileShape,
    trailing: const Icon(Icons.chevron_right),
    enabled: !_switching,
    onTap: () async {
      context.pop();
      await context.pushNamed(screen);
    },
  );

  Future<void> _switchTo(UserLoginInfo user) async {
    if (_switching || isSwitchingAccount) {
      return;
    }
    // Refused with a toast while a reply is sent on any page (see [switchAccount]).
    setState(() => _switchingUid = user.uid);
    final result = await switchAccount(context, bloc: _switchUserBloc!, userInfo: user);
    if (!mounted) {
      return;
    }
    if (result == SwitchAccountResult.switched) {
      // The pages follow the new account by themselves (`AuthStatus` subscribers); this menu was the old one's.
      Navigator.of(context).pop();
      return;
    }
    // Stays open: the toast told why, and an expired login now shows on its row.
    setState(() => _switchingUid = null);
  }

  /// Same as the manage accounts page: the login page with the name filled in, the way to make the login work again.
  Future<void> _loginAgain(UserLoginInfo user) async {
    context.pop();
    await context.pushNamed(ScreenPaths.login, queryParameters: {'username': '${user.username}'});
  }

  /// The other saved accounts, same rows and order as the manage accounts page; nothing with no other account.
  Widget _buildAccounts(BuildContext context, List<StoredAccount> accounts) {
    // Also the account whose stored session was not verified yet, like the manage accounts page.
    final currentUid = _auth!.effectiveCurrentUid;
    final others = accounts
        .where(
          (e) =>
              e.user.username != null &&
              e.user.username!.isNotEmpty &&
              e.user.uid != null &&
              e.user.uid != 0 &&
              e.user.uid != currentUid,
        )
        .toList();
    if (others.isEmpty) {
      return const SizedBox.shrink();
    }
    final tr = context.t.manageAccountPage;
    final colorScheme = Theme.of(context).colorScheme;
    final textTheme = Theme.of(context).textTheme;
    final hidden = others.length - _maxAccounts;

    Widget row(StoredAccount account) {
      final user = account.user;
      final expired = account.sessionExpiredAt != null;
      return ListTile(
        key: ValueKey('quick-switch-${user.uid}'),
        shape: _tileShape,
        enabled: !_switching,
        leading: SizedBox(
          width: 32,
          height: 32,
          // The title avatar of this dialog is the hero.
          child: HeroUserAvatar(username: user.username!, avatarUrl: avatarUrlOfUid('${user.uid}'), disableHero: true),
        ),
        title: SingleLineText(user.username!),
        subtitle: expired
            ? Text(tr.sessionExpired.hint, style: textTheme.bodySmall?.copyWith(color: colorScheme.error))
            : null,
        trailing: _switchingUid == user.uid
            ? sizedCircularProgressIndicator
            : expired
            ? const Icon(Icons.login_outlined)
            : null,
        // A dead login cannot be switched to; logging in again is the way, like on the manage accounts page.
        onTap: () async => expired ? _loginAgain(user) : _switchTo(user),
      );
    }

    return Column(
      mainAxisSize: MainAxisSize.min,
      crossAxisAlignment: CrossAxisAlignment.stretch,
      children: [
        AppSectionHeader(
          tr.switchAccount.title,
          icon: Icons.switch_account_outlined,
          padding: const EdgeInsets.fromLTRB(16, 0, 16, 4),
        ),
        ...others.take(_maxAccounts).map(row),
        if (hidden > 0)
          _entry(
            context,
            Icons.more_horiz,
            context.t.currentAccount.moreAccounts(count: hidden),
            ScreenPaths.manageAccount,
          ),
        Divider(
          height: 9,
          indent: 16,
          endIndent: 16,
          color: colorScheme.outlineVariant.withValues(alpha: 0.6),
        ),
      ],
    );
  }

  @override
  Widget build(BuildContext context) {
    // Expected containing two pairs of nodes:
    //
    // 1. My thread.
    // 2. Latest thread.

    final tr = context.t.homepage.welcome;
    final divider = Divider(
      height: 9,
      indent: 16,
      endIndent: 16,
      color: Theme.of(context).colorScheme.outlineVariant.withValues(alpha: 0.6),
    );
    final latestThreadUrl = widget.latestThreadUrl;

    // While switching, neither back nor a tap beside the dialog closes it.
    return PopScope(
      canPop: !_switching,
      child: CustomAlertDialog.sync(
        title: Row(
          children: [
            HeroUserAvatar(
              username: widget.username,
              avatarUrl: widget.avatarUrl,
              heroTag: widget.heroTag,
              minRadius: 30,
            ),
            sizedBoxW12H12,
            Expanded(
              child: SingleLineText(
                widget.username,
                style: Theme.of(context).textTheme.titleLarge?.copyWith(fontWeight: FontWeight.bold),
              ),
            ),
          ],
        ),
        // Same entries and order as before, grouped: the other accounts, the account itself, then threads, then the
        // account list.
        content: Column(
          mainAxisSize: MainAxisSize.min,
          children: [
            if (_accounts != null)
              StreamBuilder(
                stream: _accounts,
                builder: (context, snapshot) => _buildAccounts(context, snapshot.data ?? const []),
              ),
            _entry(context, Icons.person_outline, context.t.profilePage.title, ScreenPaths.profile),
            _entry(context, Icons.military_tech_outlined, context.t.medalTitleHub.title, ScreenPaths.medalTitleHub),
            divider,
            _entry(context, Icons.history_outlined, tr.history, ScreenPaths.threadVisitHistory),
            _entry(context, Icons.article_outlined, tr.myThread, ScreenPaths.myThread),
            _entry(context, Icons.star_outline, tr.favorite, ScreenPaths.favorite),
            // Switching or adding an account was only reachable through the settings page (#16).
            _entry(
              context,
              Icons.manage_accounts_outlined,
              context.t.manageAccountPage.title,
              ScreenPaths.manageAccount,
            ),
            ListTile(
              leading: const Icon(Icons.update_outlined),
              title: Text(tr.latestThread),
              shape: _tileShape,
              trailing: latestThreadUrl == null ? null : const Icon(Icons.chevron_right),
              enabled: !_switching,
              onTap: latestThreadUrl == null
                  ? null
                  : () async {
                      final target = latestThreadUrl.parseUrlToRoute();
                      if (target == null) {
                        error('invalid kahrpba link: $latestThreadUrl');
                        return;
                      }
                      context.pop();
                      await context.pushNamed(
                        target.screenPath,
                        pathParameters: target.pathParameters,
                        queryParameters: target.queryParameters,
                      );
                    },
            ),
          ],
        ),
      ),
    );
  }
}
